"""Report builder: assemble the unified non-diagnostic run report.

Reads every upstream job manifest referenced on the run document, then:
- merges `outputs.structural` from the structural analysis summary,
- merges `outputs.visualizationAssets` from the viewer-asset jobs,
- merges `outputs.evidenceLedger` from all manifest evidence items,
- writes the run's `report` summary (generatedAt, limitations,
  interpretationStatement).

The assembled report is written back to the run document and as
`report.json`. A clinical-safety scan rejects any diagnostic-sounding
language before the report is finalized.
"""

from __future__ import annotations

from jobs.common import add_safe_evidence, create_manifest
from jobs.imaging import gcs_prefix, read_json_artifact
from lib.clinical_safety import (
    GENERAL_DISCLAIMER,
    check_copy_safety,
    report_interpretation_statement,
)
from lib.firestore import update_run
from lib.manifests import utc_now
from lib.storage import write_json


UPSTREAM_JOBS = [
    "converter",
    "qc",
    "structural_prep",
    "structural_analysis",
    "structural_3d_prep",
    "diffusion_prep",
    "diffusion_analysis",
    "diffusion_3d_prep",
    "eeg_ingest",
    "eeg_prep",
    "eeg_analysis",
    "eeg_visualization_prep",
    "meg_ingest",
    "meg_prep",
    "meg_analysis",
    "meg_visualization_prep",
    "fmri_ingest",
    "fmri_prep",
    "fmri_analysis",
    "fmri_visualization_prep",
    "coregistration",
    "longitudinal_analysis",
]


def _load_manifests(context) -> dict[str, dict]:
    outputs = (context.run_doc or {}).get("outputs") or {}
    manifests: dict[str, dict] = {}
    for job_kind in UPSTREAM_JOBS:
        ref = (outputs.get(job_kind) or {}).get("manifestPath")
        if not ref:
            continue
        try:
            manifests[job_kind] = read_json_artifact(str(ref))
        except Exception as exc:
            manifests[job_kind] = {"_loadError": str(exc)}
    return manifests


def run(context) -> object:
    manifest = create_manifest(context.run_id, "report_builder")
    manifests = _load_manifests(context)
    manifest.inputs["upstreamManifests"] = sorted(manifests.keys())

    structural: dict = {}
    visualization_assets: dict = {}
    evidence_ledger: list[dict] = []
    limitations: list[str] = []
    qc_summary = "not assessed"

    for job_kind, job_manifest in manifests.items():
        if "_loadError" in job_manifest:
            manifest.warnings.append(f"Could not load {job_kind} manifest: {job_manifest['_loadError']}")
            continue
        outs = job_manifest.get("outputs") or {}

        if job_kind == "structural_analysis":
            try:
                summary = read_json_artifact(outs.get("summaryMetricsJson", ""))
                structural = summary.get("metrics", {}) or {}
                for info in (summary.get("methods") or {}).values():
                    lim = info.get("limitations")
                    if lim and lim not in limitations:
                        limitations.append(lim)
            except Exception as exc:
                manifest.warnings.append(f"Could not read structural summary: {exc}")

        if job_kind in ("structural_3d_prep", "diffusion_3d_prep", "eeg_visualization_prep", "meg_visualization_prep", "fmri_visualization_prep"):
            assets = outs.get("visualizationAssets") or {}
            visualization_assets.update(assets)

        if job_kind == "qc":
            qc_summary = outs.get("overallVerdict", qc_summary)

        for item in job_manifest.get("evidenceItems") or []:
            evidence_ledger.append({**item, "jobKind": job_kind})

        for warning in job_manifest.get("warnings") or []:
            w = f"[{job_kind}] {warning}"
            if w not in limitations:
                limitations.append(w)

    limitations.extend(
        [
            "No diagnosis, prediction, confirmation, or rule-out statement is generated by Coherence.",
            "Whole-brain averages hide regional variation.",
            "Compare only against same-protocol timepoints.",
        ]
    )
    # de-duplicate while preserving order
    limitations = list(dict.fromkeys(limitations))

    interpretation = report_interpretation_statement()
    violations = check_copy_safety(interpretation + " " + " ".join(limitations))
    if violations:
        return manifest.fail(f"Clinical-safety scan rejected report copy: {violations}")

    run_doc = context.run_doc or {}
    input_files = run_doc.get("inputFiles") or []
    report = {
        "generatedAt": utc_now(),
        "limitations": limitations,
        "interpretationStatement": interpretation,
    }

    prefix = gcs_prefix(context, "report_builder")
    report_payload = {
        "runId": context.run_id,
        "caseId": context.case_id,
        "modality": run_doc.get("modality"),
        "generatedAt": report["generatedAt"],
        "inputFiles": [{"name": f.get("name"), "sizeBytes": f.get("sizeBytes")} for f in input_files],
        "qcSummary": qc_summary,
        "structural": structural,
        "visualizationAssets": visualization_assets,
        "evidenceLedger": evidence_ledger,
        "limitations": limitations,
        "interpretationStatement": interpretation,
        "disclaimer": GENERAL_DISCLAIMER,
    }
    write_json(context.config.gcs_bucket, f"{prefix}/report.json", report_payload)
    manifest.outputs["structuredReportJson"] = f"{prefix}/report.json"

    # Publish the web-facing fields onto the run document.
    update_run(
        context.config.project_id,
        context.config.runs_collection,
        context.run_id,
        {
            "outputs": {
                "structural": structural,
                "visualizationAssets": visualization_assets,
                "evidenceLedger": evidence_ledger,
            },
            "report": report,
            "updatedAt": utc_now(),
        },
    )
    manifest.outputs["publishedFields"] = ["outputs.structural", "outputs.visualizationAssets", "outputs.evidenceLedger", "report"]

    add_safe_evidence(
        manifest, "Report assembly",
        f"{len(evidence_ledger)} evidence items, {len(visualization_assets)} viewer assets",
        "Aggregation of upstream job manifests with clinical-safety copy scan",
        GENERAL_DISCLAIMER,
    )
    return manifest.complete()

import { reportInterpretationStatement } from "../clinical-copy";
import type {
  MeasurementDelta,
  NeuroRun,
  PatientCase,
  ReportSection,
  StructuralMeasurements,
} from "../types";

function readStructural(run: NeuroRun): StructuralMeasurements {
  const raw = run.outputs?.structural;
  if (!raw || typeof raw !== "object") return {};
  const get = (key: string): number | undefined => {
    const value = (raw as Record<string, unknown>)[key];
    return typeof value === "number" ? value : undefined;
  };
  const qcRaw = (raw as Record<string, unknown>).qcFlags;
  return {
    totalIntracranialVolumeMl: get("totalIntracranialVolumeMl"),
    meanCorticalThicknessMm: get("meanCorticalThicknessMm"),
    leftHippocampusMl: get("leftHippocampusMl"),
    rightHippocampusMl: get("rightHippocampusMl"),
    qcFlags: Array.isArray(qcRaw) ? qcRaw.filter((flag): flag is string => typeof flag === "string") : undefined,
    acquisitionNotes:
      typeof (raw as Record<string, unknown>).acquisitionNotes === "string"
        ? ((raw as Record<string, unknown>).acquisitionNotes as string)
        : undefined,
  };
}

function formatNumber(value: number | undefined, unit: string): string {
  return value === undefined ? "Not available" : `${value.toFixed(2)} ${unit}`;
}

/** Builds the structured, non-diagnostic sections of a structural MRI report. */
export function buildStructuralReportSections(run: NeuroRun, patientCase?: PatientCase | null): ReportSection[] {
  const measurements = readStructural(run);
  const modalityLabel = run.modality.replace(/_/g, " ");
  const generatedAt = run.report?.generatedAt ?? run.updatedAt;

  const sections: ReportSection[] = [
    {
      id: "administrative",
      title: "Administrative details",
      body: "Run identification, data inputs, and processing state for this report.",
      rows: [
        { label: "Case", value: patientCase?.displayName ?? run.caseId },
        { label: "Run", value: run.id },
        { label: "Modality", value: modalityLabel },
        { label: "Report generated", value: generatedAt.slice(0, 10) },
        { label: "Pipeline status", value: run.status },
      ],
    },
    {
      id: "inputs",
      title: "Data inputs",
      body:
        run.inputFiles.length > 0
          ? `${run.inputFiles.length} registered input file(s) were attached to this run.`
          : "No input files are attached to this run in the current view.",
      rows: run.inputFiles.map((file) => ({
        label: file.name,
        value: `${(file.sizeBytes / 1024 / 1024).toFixed(1)} MB · uploaded ${file.uploadedAt.slice(0, 10)}`,
      })),
    },
    {
      id: "qc",
      title: "Quality-control summary",
      tone: measurements.qcFlags?.length ? "caution" : "info",
      body:
        measurements.qcFlags?.length
          ? "Automated quality-control flags for clinician review. Flags describe acquisition and processing quality only."
          : "Quality-control flags will appear here when backend processing completes.",
      rows: (measurements.qcFlags ?? []).map((flag, index) => ({ label: `Flag ${index + 1}`, value: flag })),
    },
    {
      id: "measurements",
      title: "Structural measurements",
      body: "Whole-brain and regional measurement summaries. Values are supplementary context for clinician review, not diagnostic markers.",
      rows: [
        { label: "Total intracranial volume", value: formatNumber(measurements.totalIntracranialVolumeMl, "mL") },
        { label: "Mean cortical thickness", value: formatNumber(measurements.meanCorticalThicknessMm, "mm") },
        { label: "Left hippocampus", value: formatNumber(measurements.leftHippocampusMl, "mL") },
        { label: "Right hippocampus", value: formatNumber(measurements.rightHippocampusMl, "mL") },
      ],
    },
  ];

  if (measurements.acquisitionNotes) {
    sections.push({
      id: "acquisition",
      title: "Acquisition notes",
      body: measurements.acquisitionNotes,
      tone: "info",
    });
  }

  const limitations = run.report?.limitations?.length
    ? run.report.limitations
    : ["No diagnostic conclusion is generated by Coherence."];

  sections.push({
    id: "limitations",
    title: "Limitations",
    tone: "caution",
    body: "Read these limits before acting on any value in this report.",
    rows: limitations.map((limitation, index) => ({ label: `Limit ${index + 1}`, value: limitation })),
  });

  sections.push({
    id: "interpretation",
    title: "Non-diagnostic interpretation statement",
    tone: "info",
    body: run.report?.interpretationStatement ?? reportInterpretationStatement,
  });

  return sections;
}

function deltaRow(label: string, prior: number | undefined, latest: number | undefined, unit: string): MeasurementDelta | null {
  if (prior === undefined || latest === undefined) return null;
  const change = latest - prior;
  const pct = prior !== 0 ? (change / prior) * 100 : 0;
  const sign = change > 0 ? "+" : change < 0 ? "−" : "±";
  return {
    label,
    prior: `${prior.toFixed(2)} ${unit}`,
    latest: `${latest.toFixed(2)} ${unit}`,
    change: `${sign}${Math.abs(change).toFixed(2)} ${unit} (${sign}${Math.abs(pct).toFixed(2)}%)`,
    unit,
    note: "Small changes may sit within expected measurement variability; compare acquisition quality flags before interpreting any shift.",
  };
}

/** Compares two structural timepoints; used by the longitudinal comparison view. */
export function compareStructuralRuns(prior: NeuroRun, latest: NeuroRun): MeasurementDelta[] {
  const priorM = readStructural(prior);
  const latestM = readStructural(latest);
  return [
    deltaRow("Total intracranial volume", priorM.totalIntracranialVolumeMl, latestM.totalIntracranialVolumeMl, "mL"),
    deltaRow("Mean cortical thickness", priorM.meanCorticalThicknessMm, latestM.meanCorticalThicknessMm, "mm"),
    deltaRow("Left hippocampus", priorM.leftHippocampusMl, latestM.leftHippocampusMl, "mL"),
    deltaRow("Right hippocampus", priorM.rightHippocampusMl, latestM.rightHippocampusMl, "mL"),
  ].filter((row): row is MeasurementDelta => row !== null);
}
